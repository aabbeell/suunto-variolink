// ABOUTME: Registers the vario's NMEA stream (service 0xFFE0, characteristic 0xFFE1) in one of two UUID forms:
// ABOUTME: id 1 = plain 2-byte arrays (the form the Race S accepts), id 2 = base-expanded 16-byte little-endian arrays.
function (c, k) {
  if (k == 1) {
    appConn.regUuid(c, 1, [0xE0, 0xFF], [0xE1, 0xFF]);
  } else {
    appConn.regUuid(c, 2,
      [0xFB, 0x34, 0x9B, 0x5F, 0x80, 0x00, 0x00, 0x80, 0x00, 0x10, 0x00, 0x00, 0xE0, 0xFF, 0x00, 0x00],
      [0xFB, 0x34, 0x9B, 0x5F, 0x80, 0x00, 0x00, 0x80, 0x00, 0x10, 0x00, 0x00, 0xE1, 0xFF, 0x00, 0x00]);
  }
}
